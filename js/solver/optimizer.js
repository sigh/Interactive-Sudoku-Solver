export class SudokuConstraintOptimizer {
  // Maximum number of cells in some sums generated by the optimizers.
  _MAX_SUM_SIZE = 6;

  constructor(debugLogger) {
    this._debugLogger = null;
    if (debugLogger.enableLogs) {
      this._debugLogger = debugLogger;
    }
    this._forbiddenStackPool = null;
  }

  _logAddHandler(loc, handler, { args = null, cells = null, aux = false } = {}) {
    if (!this._debugLogger) return;

    const auxSuffix = aux ? ' (aux)' : '';

    const entry = {
      loc,
      msg: 'Add: ' + handler.constructor.name + auxSuffix,
    };

    if (args) entry.args = args;
    if (cells) entry.cells = cells;
    else if (handler.cells) entry.cells = handler.cells;

    this._debugLogger.log(entry);
  }

  optimize(handlerSet, cellExclusions, geometry) {
    const boxRegionInfo = handlerSet.getAllofType(HandlerModule.BoxRegionInfo)[0];
    const boxRegions = boxRegionInfo?.boxRegions() || [];

    this._addExtraCellExclusions(handlerSet, cellExclusions, geometry);

    const effectiveValues = this._computeEffectiveValues(handlerSet, geometry);

    this._addPerfectAllDifferentHandlers(handlerSet, geometry, effectiveValues);


    if (geometry.gridType === CellGeometry.SUDOKU_GRID_TYPE &&
      !geometry.isSquare()) {
      this._optimizeNonSquareGrids(handlerSet, boxRegions, geometry);
    }

    const effectiveValueInfo = this._effectiveValueInfo(effectiveValues, geometry);

    this._optimizeSums(
      handlerSet, cellExclusions, boxRegions, geometry, effectiveValueInfo);

    this._optimizeRellik(handlerSet, geometry);

    this._optimizeJigsaw(
      handlerSet, boxRegions, geometry, effectiveValueInfo.count);

    this._optimizeFullRank(handlerSet, geometry);

    this._optimizeChaosConstruction(handlerSet, geometry, effectiveValueInfo.mask);

    this._mergeConnectedValues(handlerSet, geometry);

    this._optimizeRequiredValues(handlerSet, cellExclusions, geometry);

    this._optimizeTaxicab(handlerSet, cellExclusions, geometry);

    this._optimizeBinaryPairwise(handlerSet, geometry);

    this._addGridHouseIntersections(handlerSet, boxRegions, geometry);

    const cellPriorities = this._computeCellPriorities(handlerSet, geometry);
    this._selectPriorityAnchorCells(handlerSet, geometry, cellPriorities);

    this._logStats(handlerSet);
    return cellPriorities;
  }

  // Cell priorities are used to determine the order in which cells are
  // searched with preference given to cells with higher priority.
  _computeCellPriorities(handlerSet, geometry) {
    const priorities = new Int32Array(geometry.totalCells());

    // TODO: Determine priorities in a more principled way.
    //  - Add one for each exclusion cell.
    //  - Add custom priorities for each constraint based on how restrictive it
    //    is.

    for (const handler of handlerSet) {
      const priority = handler.priority(geometry);
      for (const cell of handler.cells) {
        priorities[cell] += priority;
      }
    }

    this._boostLinkedCellPriorities(priorities, handlerSet, geometry);

    for (const handler of handlerSet.getAllofType(HandlerModule.SearchPriority)) {
      for (const cell of handler.priorityCells()) {
        priorities[cell] = handler.priority(geometry);
      }
    }

    if (this._debugLogger) {
      this._debugLogger.log({
        loc: '_computeCellPriorities',
        msg: 'Hover for values',
        args: {
          min: Math.min(...priorities),
          max: Math.max(...priorities),
        },
        overlay: priorities,
      });
    }

    return priorities;
  }

  _boostLinkedCellPriorities(priorities, handlerSet, geometry) {
    const linkedCells = buildLinkedSearchCells(handlerSet, priorities.length);
    if (linkedCells === null) return;

    const minLinkedPriority = Math.max(10, geometry.numValues + 1);
    const marks = new Uint32Array(priorities.length);
    let mark = 0;
    for (const handler of handlerSet) {
      const priority = handler.priority(geometry);
      if (priority < minLinkedPriority) continue;

      mark++;
      for (const cell of handler.cells) marks[cell] = mark;

      for (const cell of handler.cells) {
        const linkedCell = linkedCells[cell];
        if (linkedCell === NO_LINKED_CELL || cell > linkedCell) continue;
        if (marks[linkedCell] !== mark) continue;

        priorities[cell] += priority;
        priorities[linkedCell] += priority;
      }
    }
  }

  _mergeConnectedValues(handlerSet, geometry) {
    const handlers = handlerSet.getAllofType(
      ConnectedHandlerModule.ConnectedValues);
    if (handlers.length < 2) return;

    // ConnectedValues cells are always a whole layer in order, so the
    // layer's first cell identifies the cell list.
    const byLayer = new Map();
    for (const h of handlers) {
      const key = h.cells[0];
      if (!byLayer.has(key)) byLayer.set(key, []);
      byLayer.get(key).push(h);
    }

    for (const group of byLayer.values()) {
      if (group.length < 2) continue;

      // Merged handlers require pairwise-disjoint single-value sets (a
      // cell is decided into at most one set, and multi-value sets are
      // only supported alone); leave other instances separate.
      const sets = new Map(group.flatMap(h => [...h.sets()]));
      const valueSets = [...sets.keys()];
      if (valueSets.some(values => values.length !== 1)) continue;
      const allValues = valueSets.flat();
      if (new Set(allValues).size !== allValues.length) continue;

      const cellOffset = group[0].cells[0];
      const newHandler = new ConnectedHandlerModule.ConnectedValues(
        group[0].cells.length, cellOffset, sets);
      handlerSet.replace(group[0], newHandler);
      newHandler.essential = group.some(h => h.essential);
      for (let i = 1; i < group.length; i++) handlerSet.delete(group[i]);
      this._logAddHandler('_mergeConnectedValues', newHandler, {
        args: { valueSets },
      });

      this._addConnectedCrossingRules(
        handlerSet, geometry, newHandler.cells, valueSets.length, allValues);
    }
  }

  // Add the joint crossing/border rules for a merged ConnectedValues layer.
  _addConnectedCrossingRules(handlerSet, geometry, cells, numSets, values) {
    const graph = geometry.cellGraph();
    const extra = [];

    // Crossing rule: one handler per 2x2 block — a cell with a right, down and
    // diagonal neighbour in the layer.
    for (const nw of cells) {
      const ne = graph.traverse(nw, 0, 1);
      const sw = graph.traverse(nw, 1, 0);
      const se = graph.traverse(nw, 1, 1);
      if (ne !== null && sw !== null && se !== null) {
        extra.push(new ConnectedHandlerModule.ConnectedCrossing(
          [nw, ne, sw, se], values));
      }
    }

    // Border rule (two sets only, and only where a cycle exists)
    if (numSets === 2) {
      extra.push(new ConnectedHandlerModule.ConnectedBorder(
        graph.perimeter(cells[0]), values));
    }

    handlerSet.addNonEssential(...extra);
    for (const h of extra) {
      this._logAddHandler('_addConnectedCrossingRules', h);
    }
  }

  _optimizeChaosConstruction(handlerSet, geometry, effectiveValueMask) {
    const chaosHandlers = handlerSet.getAllofType(ChaosHandlerModule.ChaosConstruction);
    if (chaosHandlers.length === 0) return;

    const regionCells = geometry.varCellsForGroup('CC');
    const numGridCells = geometry.numGridCells;
    if (!regionCells || regionCells.length !== numGridCells) return;

    const regionCellOffset = regionCells[0];
    // Shared context so each sub-optimization skips the region-cell lookups.
    const chaos = {
      chaosHandlers,
      numGridCells,
      regionCellOffset,
      regionCellLimit: regionCellOffset + numGridCells,
    };

    this._addChaosFixedValueRegionExclusions(handlerSet, chaos);
    this._addChaosRegionShardSources(handlerSet, geometry, effectiveValueMask, chaos);
    this._addChaosCountDistinctMaxBounds(handlerSet, geometry, chaos);
  }

  _addChaosFixedValueRegionExclusions(handlerSet, chaos) {
    const { numGridCells, regionCellOffset } = chaos;
    for (let i = 0; i < numGridCells; i++) {
      handlerSet.add(
        new ChaosHandlerModule.ChaosFixedValueRegionExclusion(
          i, i, numGridCells, regionCellOffset),
        new ChaosHandlerModule.ChaosFixedValueRegionExclusion(
          i, regionCellOffset + i, numGridCells, regionCellOffset));
    }
  }

  _addChaosRegionShardSources(handlerSet, geometry, effectiveValueMask, chaos) {
    const { chaosHandlers, regionCellOffset, regionCellLimit } = chaos;

    const arrowHandlers = handlerSet.getAllofType(ChaosHandlerModule.ChaosArrow);
    const countHandlers = handlerSet.getAllofType(ChaosHandlerModule.ChaosCount);

    const equalsKey = SudokuConstraintOptimizer._equalsKey(geometry.numValues);
    const binaryHandlers = [
      ...handlerSet.getAllofType(HandlerModule.BinaryConstraint),
      ...handlerSet.getAllofType(HandlerModule.BinaryPairwise)];
    const links = [];
    for (const handler of binaryHandlers) {
      if (handler.key() !== equalsKey) continue;
      const cells = handler.cells;
      for (let i = 1; i < cells.length; i++) {
        const regionCellA = cells[i];
        if (regionCellA < regionCellOffset || regionCellA >= regionCellLimit) continue;
        const cellA = regionCellA - regionCellOffset;
        for (let j = 0; j < i; j++) {
          const regionCellB = cells[j];
          if (regionCellB < regionCellOffset || regionCellB >= regionCellLimit) continue;
          const cellB = regionCellB - regionCellOffset;
          const delta = Math.abs(cellA - cellB);
          if (delta === geometry.numCols
            || (delta === 1 && (cellA / geometry.numCols | 0) === (cellB / geometry.numCols | 0))) {
            links.push([cellA, cellB]);
          }
        }
      }
    }

    for (const handler of chaosHandlers) {
      handler.setEffectiveValueMask(effectiveValueMask);
      for (const link of links) handler.addRegionLink(link);
      for (const arrowHandler of arrowHandlers) {
        arrowHandler.attachRegionShardState(handler.regionShardState());
      }
      for (const countHandler of countHandlers) {
        countHandler.attachRegionShardState(handler.regionShardState());
      }
    }
  }

  _addChaosCountDistinctMaxBounds(handlerSet, geometry, chaos) {
    const countHandlers = handlerSet.getAllofType(HandlerModule.CountDistinct);
    if (countHandlers.length === 0) return;

    const { regionCellOffset, regionCellLimit } = chaos;

    for (const handler of countHandlers) {
      // cells[0] is the control; only counted sets entirely in the region lane
      // carry region-adjacency structure. The smallest enclosed configuration is
      // a corner cell with its two neighbours, so anything smaller can't help.
      const cells = handler.cells;
      const numCounted = cells.length - 1;
      if (numCounted < 3) continue;
      const countedGridCells = new Set();
      let allRegionLane = true;
      for (let i = 1; i < cells.length; i++) {
        const regionCell = cells[i];
        if (regionCell < regionCellOffset || regionCell >= regionCellLimit) {
          allRegionLane = false;
          break;
        }
        countedGridCells.add(regionCell - regionCellOffset);
      }
      if (!allRegionLane) continue;

      const reduction = this._countEnclosedRegionCoincidences(countedGridCells, geometry);
      if (reduction === 0) continue;

      // The control cell's value is the distinct count, so cap it at the reduced
      // maximum. Skip when the handler's own bound (min(numCounted, numValues))
      // is already at least this tight.
      const maxDistinct = numCounted - reduction;
      if (maxDistinct >= geometry.numValues) continue;
      // Keep only the lowest maxDistinct count-bits; count k occupies value bit
      // k - offset - 1, matching the handler's own range encoding.
      const keepMask = (1 << (maxDistinct - geometry.valueOffset)) - 1;
      const allowed = LookupTables.toOffsetValuesArray(keepMask, geometry.valueOffset);

      const newHandler = new HandlerModule.GivenCandidates(
        new Map([[cells[0], allowed]]));
      handlerSet.add(newHandler);
      if (this._debugLogger) {
        this._logAddHandler('_addChaosCountDistinctMaxBounds', newHandler, {
          args: { maxDistinct },
          cells: handler.cells,
        });
      }
    }
  }

  // Greedily counts enclosed counted cells whose closed neighbourhoods are
  // pairwise disjoint. Each enclosed cell forces one same-region pair within the
  // set; keeping the neighbourhoods disjoint keeps those pairs cell-disjoint, so
  // the count is a sound lower bound on the number of forced coincidences (hence
  // on the reduction in distinct labels).
  _countEnclosedRegionCoincidences(countedGridCells, geometry) {
    const neighborTable = ConnectedHandlerModule.neighborTable(
      geometry.numRows, geometry.numCols);
    const used = new Set();
    let reduction = 0;

    for (const cell of countedGridCells) {
      const neighbors = ConnectedHandlerModule.enclosingNeighbors(
        neighborTable, cell, countedGridCells);
      if (neighbors === null) continue;

      // Take the coincidence only if its closed neighbourhood is untouched, so
      // the forced same-region pairs stay cell-disjoint across selections.
      if (used.has(cell) || neighbors.some(n => used.has(n))) continue;

      reduction++;
      used.add(cell);
      for (const neighbor of neighbors) used.add(neighbor);
    }

    return reduction;
  }

  _selectPriorityAnchorCells(handlerSet, geometry, cellPriorities) {
    for (const handler of handlerSet.getAllofType(ChaosHandlerModule.ChaosConstruction)) {
      handler.selectPriorityAnchorCells(geometry, cellPriorities);
    }
  }

  _optimizeNonSquareGrids(handlerSet, boxRegions, geometry) {
    // For non-square grids without boxes, one axis forms houses
    // and the other axis has numValues lines of length K < numValues.
    // Since those K-length lines are all-different then for each value it must
    // appear in exactly K of those numValues lines.
    // Add an auxiliary handler that propagates this fact.

    // Note: Without this empty grids can be VERY slow. However, when there are
    // some constraints (or possibly just deeper into the solve) this constraint
    // just slows things down.
    // However, rectangular grids without boxes are relatively rare, so it's
    // ok to just ensure that we avoid the worst cases here.

    // We don't need this if there are boxes, as the box constraints provide
    // sufficient propagation.
    if (boxRegions.length > 0) return;

    // Determine the axis that has numValues *lines* (the longer dimension).
    // Those lines have length K = min(numRows, numCols).
    let lines;
    let requiredLineCount;
    const numValues = geometry.numValues;

    if (geometry.numCols === numValues) {
      // Columns: numValues lines, each with numRows cells.
      lines = SudokuConstraintBase.colRegions(geometry);
      requiredLineCount = geometry.numRows;
    } else if (geometry.numRows === numValues) {
      // Rows: numValues lines, each with numCols cells.
      lines = SudokuConstraintBase.rowRegions(geometry);
      requiredLineCount = geometry.numCols;
    }

    // This optimization assumes that the longer dimension equals numValues.
    // With non-default numValues (e.g. 9x9~10), that assumption doesn't hold,
    // so skip this optimization.
    if (!lines) return;
    // If we only have 1 line, this constraint has no effect.
    // If we have 2 lines, then only there is minimal propagation possible,
    // because its not very constraining.
    if (requiredLineCount <= 2) return;

    // Pack all line cell indices into one backing store and create per-line views.
    const backing = Uint16Array.from(lines.flat());
    const packedLines = lines.map(
      (_, i) => backing.subarray(
        requiredLineCount * i,
        requiredLineCount * (i + 1)));

    const handler = new HandlerModule.FullGridRequiredValues(
      allCells(geometry),
      packedLines);
    handlerSet.addAux(handler);
    this._logAddHandler('_addFullGridRequiredValues', handler, {
      aux: true,
      args: { requiredLineCount },
    });
  }

  static _equalsKey = memoize((numValues) => fnToBinaryKey(
    (a, b) => a === b, numValues));

  _addExtraCellExclusions(handlerSet, cellExclusions, geometry) {
    // If two cells must have the same value, then they have to share the same
    // cell exclusions.
    // This will allow Palindrome and SameValue constraints to propagate their
    // restrictions better.
    const binaryHandlers = [
      ...handlerSet.getAllofType(
        HandlerModule.BinaryConstraint),
      ...handlerSet.getAllofType(
        HandlerModule.BinaryPairwise)];
    const equalsKey = SudokuConstraintOptimizer._equalsKey(geometry.numValues);

    for (const h of binaryHandlers) {
      if (h.key() !== equalsKey) continue;
      for (let i = 1; i < h.cells.length; i++) {
        for (let j = 0; j < i; j++) {
          cellExclusions.areSameValue(h.cells[i], h.cells[j]);
        }
      }
    }
  }

  _addGridHouseIntersections(handlerSet, boxRegions, geometry) {
    // Intersections are not very useful if there are no boxes.
    if (boxRegions.length === 0) return;
    const boxSize = boxRegions[0].length;

    const [boxHeight, boxWidth] = CellGeometry.boxDimsForSize(
      geometry.numRows, geometry.numCols, boxSize);
    if (!boxHeight) return;

    const allHandlers = handlerSet.getAllofType(
      HandlerModule.PerfectAllDifferent).filter(
        h => h.cells.length === boxSize);

    const numHandlers = allHandlers.length;

    // Every house is tested against every other, so hold them as bitsets.
    const { bitsets: houseCells } = BitSet.allocatePool(
      geometry.totalCells(), numHandlers);
    for (let i = 0; i < numHandlers; i++) {
      for (const cell of allHandlers[i].cells) houseCells[i].add(cell);
    }

    for (let i = 1; i < numHandlers; i++) {
      for (let j = 0; j < i; j++) {
        if (allHandlers[i].valueMask() !== allHandlers[j].valueMask()) continue;
        const intersectionSize = houseCells[i].intersectCount(houseCells[j]);
        if (intersectionSize !== boxWidth && intersectionSize !== boxHeight) continue;
        const onlyInI = houseCells[i].clone();
        onlyInI.subtract(houseCells[j]);
        const onlyInJ = houseCells[j].clone();
        onlyInJ.subtract(houseCells[i]);
        const newHandler = new HandlerModule.SameValuesIgnoreCount(
          onlyInI.toSortedArray(), onlyInJ.toSortedArray());
        handlerSet.addAux(newHandler);
        this._logAddHandler(
          '_addGridHouseIntersections', newHandler, { aux: true });
      }
    }
  }

  _optimizeJigsaw(handlerSet, boxRegions, geometry, effectiveValueCount) {
    const jigsawPieces = handlerSet.getAllofType(HandlerModule.JigsawPiece);
    if (jigsawPieces.length === 0) return;

    handlerSet.addNonEssential(
      ...this._makeJigsawIntersections(handlerSet, jigsawPieces));

    handlerSet.addNonEssential(
      ...this._makeJigsawLawOfLeftoverHandlers(
        jigsawPieces, boxRegions, geometry, effectiveValueCount));
  }

  // Find a non-overlapping set of handlers.
  // `intersectionCache` is an optional Map for reusing getIntersectingIndexes
  // results across calls -- see the caller for when that is valid.
  _findNonOverlappingSubset(handlers, fullHandlerSet, intersectionCache = null) {
    const handlerIndexes = new BitSet(fullHandlerSet.numHandlers());
    for (const h of handlers) handlerIndexes.add(fullHandlerSet.getIndex(h));

    // Sort handers by number of overlapping handlers.
    const handlersByOverlaps = [];
    for (const h of handlers) {
      let overlapIndexes = intersectionCache?.get(h);
      if (overlapIndexes === undefined) {
        overlapIndexes = fullHandlerSet.getIntersectingIndexes(h);
        intersectionCache?.set(h, overlapIndexes);
      }
      const numOverlap = overlapIndexes.intersectCount(handlerIndexes);
      handlersByOverlaps.push([h, numOverlap]);
    }
    handlersByOverlaps.sort((a, b) => a[1] - b[1]);

    // Find a set of mutually non-overlapping handlers.
    // Start with the handlers with the least overlaps as they restrict future
    // choices the least.
    // i.e. greedy bin-packing.
    const cellsIncluded = new BitSet(fullHandlerSet.numSearchCells());
    const nonOverlappingHandlers = [];
    for (const [h,] of handlersByOverlaps) {
      if (h.cells.some(c => cellsIncluded.has(c))) continue;
      nonOverlappingHandlers.push(h);
      h.cells.forEach(c => cellsIncluded.add(c));
    }

    return nonOverlappingHandlers;
  }

  _optimizeSums(handlerSet, cellExclusions, boxRegions, geometry, effectiveValueInfo) {
    // TODO: Consider how this interacts with fixed cells.
    const allSumHandlers = handlerSet.getAllofType(SumHandlerModule.Sum);
    if (allSumHandlers.length === 0) return;
    // Exclude any handlers with duplicate cells from any of the optimizations.
    // TODO: Check which optimizations are still valid.
    // Also exclude 0-cell handlers (e.g. from cancelled makeEqual) as they
    // have no cells to optimize over.
    const safeSumHandlers = allSumHandlers.filter(
      h => h.onlyUnitCoeffs() && h.cells.length > 0);

    const filteredSumHandlers =
      this._findNonOverlappingSubset(safeSumHandlers, handlerSet);

    handlerSet.addNonEssential(
      ...this._fillInSumGap(filteredSumHandlers, geometry));

    handlerSet.addNonEssential(
      ...this._makeInnieOutieSumHandlers(
        filteredSumHandlers, boxRegions, geometry,
        effectiveValueInfo.count, effectiveValueInfo.sum));

    handlerSet.addNonEssential(
      ...this._makeHiddenCageHandlers(handlerSet, safeSumHandlers, cellExclusions, geometry));

    handlerSet.addNonEssential(
      ...this._makeCombinedSumHandlers(safeSumHandlers, cellExclusions, geometry));

    this._replaceSizeSpecificSumHandlers(handlerSet, cellExclusions, geometry);

    // Don't pass in the sum handlers so that this phase can operate on all the
    // new sum handlers that were added.
    this._addSumComplementCells(handlerSet);

    return;
  }

  _makeCombinedSumHandlers(allSumHandlers, cellExclusions, geometry) {
    // Bounded, greedy merge process:
    // - Assign a score to each record
    // - Only merge two records if the merged score is strictly better than BOTH inputs.
    // - Once merged, the two inputs are removed and only the merged record remains.
    // This prevents exponential blowup.

    const scoreOf = (groups, dof) => {
      let score = 0;
      for (const g of groups) {
        const k = g.length;
        // How much "slack" this group provides beyond the dof.
        score += k * (geometry.numValues - k) - dof;
      }
      return score;
    };

    const keyFromSortedCells = (cells) => cells.join(',');

    const recordFromCellsAndSum = (cells, sum, original, key) => {
      const groups = HandlerModule.HandlerUtil.findExclusionGroupsGreedy(
        cells, cellExclusions).groups;
      const { range, min, max } = HandlerModule.HandlerUtil.exclusionGroupSumInfo(
        groups, geometry.numValues, geometry.valueOffset);
      if (sum < min || sum > max) return null;

      const dof = Math.min(sum - min, max - sum);
      const cellsBitSet = new BitSet(cellExclusions.numSearchCells());
      for (const c of cells) cellsBitSet.add(c);

      return {
        key: key || keyFromSortedCells(cells),
        cells, cellsBitSet,
        sum, range, dof,
        score: scoreOf(groups, dof),
        original,
      };
    };

    const areRelatedNonOverlapping = (r1, r2) => {
      // Disallow overlap.
      if (r1.cellsBitSet.hasIntersection(r2.cellsBitSet)) return false;

      // Related iff there exists at least 6 cells with exclusion edges between
      // the sets.
      const MIN_OVERLAP_COUNT = 6;
      const [small, big] = r2.cells.length < r1.cells.length
        ? [r2, r1] : [r1, r2];
      if (small.cells.length < MIN_OVERLAP_COUNT) return false;
      let count = 0;
      for (const cell of small.cells) {
        if (cellExclusions.getBitSet(cell).hasIntersection(big.cellsBitSet)) {
          if (++count >= MIN_OVERLAP_COUNT) return true;
        }
      }
      return false;
    };

    const isBetterCandidate = (a, b) => {
      if (a.score !== b.score) return a.score > b.score;
      // Deterministic tie-breaker: prefer lexicographically-larger key.
      return a.key > b.key;
    };

    // Active pool keyed by sorted cell list.
    const activeByKey = new Map();

    const candidates = [];
    const pushCandidate = (r1, r2) => {
      if (!areRelatedNonOverlapping(r1, r2)) return;

      const combinedCells = mergeSortedArrays(r1.cells, r2.cells);
      const combinedKey = keyFromSortedCells(combinedCells);
      if (activeByKey.has(combinedKey)) return;

      const combinedSum = r1.sum + r2.sum;
      const combinedRecord = recordFromCellsAndSum(
        combinedCells, combinedSum, false, combinedKey);
      if (!combinedRecord) return;

      // Accept if strictly better than both inputs, or better than their sum.
      if (combinedRecord.score <= r1.score || combinedRecord.score <= r2.score) {
        if (combinedRecord.score <= r1.score + r2.score) return;
      }

      candidates.push({
        score: combinedRecord.score,
        key: combinedKey,
        r1,
        r2,
        combined: combinedRecord,
      });
    };

    for (const h of allSumHandlers) {
      const cells = sortedArrayCopy(h.cells);

      const r = recordFromCellsAndSum(cells, h.sum(), true);
      if (!r) continue;

      // Prefer first occurrence if duplicates exist.
      if (activeByKey.has(r.key)) continue;
      activeByKey.set(r.key, r);
    }

    // Initial candidate generation.
    const initialRecords = [...activeByKey.values()];
    for (let i = 0; i < initialRecords.length; i++) {
      for (let j = i + 1; j < initialRecords.length; j++) {
        pushCandidate(initialRecords[i], initialRecords[j]);
      }
    }

    // Apply merges in descending score order.
    while (true) {
      let bestIdx = -1;
      let bestCand = null;
      for (let i = 0; i < candidates.length; i++) {
        const cand = candidates[i];

        // Skip invalidated candidates (parents removed or combined already exists).
        if (activeByKey.get(cand.r1.key) !== cand.r1
          || activeByKey.get(cand.r2.key) !== cand.r2
          || activeByKey.has(cand.combined.key)) {
          // Swap-remove invalid candidate.
          candidates[i] = candidates[candidates.length - 1];
          candidates.pop();
          if (bestIdx === candidates.length) bestIdx = i;
          i--;
          continue;
        }

        if (!bestCand || isBetterCandidate(cand, bestCand)) {
          bestCand = cand;
          bestIdx = i;
        }
      }
      if (!bestCand) break;

      // Swap-remove chosen candidate.
      candidates[bestIdx] = candidates[candidates.length - 1];
      candidates.pop();

      const best = bestCand.combined;
      activeByKey.delete(bestCand.r1.key);
      activeByKey.delete(bestCand.r2.key);
      activeByKey.set(best.key, best);

      // Only new pairs involving the merged record can become valid.
      for (const other of activeByKey.values()) {
        if (other === best) continue;
        pushCandidate(best, other);
      }
    }

    // Instantiate handlers only for inferred sums with sufficient score.
    const newHandlers = [];
    for (const r of activeByKey.values()) {
      if (r.original || r.score <= 0) continue;
      newHandlers.push(new SumHandlerModule.Sum(r.cells, r.sum));
      this._debugLogger?.log({
        loc: '_makeCombinedSumHandlers',
        msg: 'Add: ' + SumHandlerModule.Sum.name,
        args: { sum: r.sum, range: r.range, dof: r.dof, score: r.score },
        cells: r.cells,
      });
    }

    return newHandlers;
  }

  _findCommonHandlers(cells, handlerSet, handlerIndexes) {
    const cellMap = handlerSet.getOrdinaryHandlerMap();

    let commonHandlers = handlerIndexes;
    for (const c of cells) {
      commonHandlers = arrayIntersect(commonHandlers, cellMap[c]);
      if (commonHandlers.length === 0) return commonHandlers;
    }

    return commonHandlers;
  }

  _addSumComplementCells(handlerSet) {
    const allDiffHandlerIndexes = handlerSet.getAllofType(
      HandlerModule.PerfectAllDifferent).map(h => handlerSet.getIndex(h));

    for (const h of handlerSet.getAllofType(SumHandlerModule.Sum)) {
      if (!h.onlyUnitCoeffs()) continue;

      const cells = h.cells;
      const commonHandlers = this._findCommonHandlers(
        cells, handlerSet, allDiffHandlerIndexes);
      if (commonHandlers.length === 0) continue;
      // Prefer the smallest containing handler: fewer complement cells and a
      // tighter valueMask give stronger propagation.
      let commonHandler = handlerSet.getHandler(commonHandlers[0]);
      for (let i = 1; i < commonHandlers.length; i++) {
        const h = handlerSet.getHandler(commonHandlers[i]);
        if (h.cells.length < commonHandler.cells.length) {
          commonHandler = h;
        }
      }

      const complementCells = arrayDifference(commonHandler.cells, cells);
      h.setComplementCells(complementCells, commonHandler.valueMask());

      if (this._debugLogger) {
        this._debugLogger.log({
          loc: '_addSumComplementCells',
          msg: 'Set complement cells',
          cells: complementCells
        });
      }
    }
  }

  _fillInSumGap(sumHandlers, geometry) {
    // The grid total is only known when the rows are Sudoku houses.
    if (geometry.gridType !== CellGeometry.SUDOKU_GRID_TYPE) return [];
    // Fill in a gap if one remains.
    // Exclude handlers with cells outside the grid.
    const gridHandlers = sumHandlers.filter(
      h => h.cells.every(c => c < geometry.numGridCells));
    if (gridHandlers.length === 0) return [];

    const numNonSumCells = geometry.numGridCells - gridHandlers.reduce(
      (n, h) => n + h.cells.length, 0);
    if (numNonSumCells === 0 || numNonSumCells >= geometry.numValues) return [];

    const sumHandlersSum = gridHandlers.map(h => h.sum()).reduce((a, b) => a + b);
    const numRegions = geometry.numGridCells / geometry.numValues;
    const remainingSum = numRegions * maxSumForShape(geometry) - sumHandlersSum;

    const remainingCells = new Set(allCells(geometry));
    gridHandlers.forEach(h => h.cells.forEach(c => remainingCells.delete(c)));
    const newHandler = new SumHandlerModule.Sum(
      [...remainingCells], remainingSum);

    sumHandlers.push(newHandler);

    if (this._debugLogger) {
      this._logAddHandler('_fillInSumGap', newHandler, {
        args: { sum: remainingSum },
      });
    }

    return [newHandler];
  }

  // Compute per-cell effective values by applying GivenCandidates
  // restrictions to a scratch grid.
  _computeEffectiveValues(handlerSet, geometry) {
    const numCells = geometry.totalCells();
    const allValues = LookupTables.allValues(geometry.numValues);
    const effectiveValues = new Uint16Array(numCells);
    effectiveValues.fill(allValues);
    for (const h of
      handlerSet.getAllofType(HandlerModule.GivenCandidates)) {
      h.applyValues(effectiveValues, geometry.valueOffset);
    }
    return effectiveValues;
  }

  _effectiveValueInfo(effectiveValues, geometry) {
    let gridValues = 0;
    for (let i = 0; i < geometry.numGridCells; i++) {
      gridValues |= effectiveValues[i];
    }
    const count = countOnes16bit(gridValues);
    return {
      count,
      sum: LookupTables.get(geometry.numValues).sum[gridValues]
        + geometry.valueOffset * count,
      mask: gridValues,
    };
  }

  _effectiveValueCount(effectiveValues, geometry) {
    return this._effectiveValueInfo(effectiveValues, geometry).count;
  }

  // Promote AllDifferent handlers to PerfectAllDifferent as appropriate.
  _addPerfectAllDifferentHandlers(handlerSet, geometry, effectiveValues) {
    for (const h of
      handlerSet.getAllofType(HandlerModule.AllDifferent)) {
      const cells = h.exclusionCells();
      if (cells.length <= 2) continue;

      let valueMask = 0;
      for (let i = 0; i < cells.length; i++) {
        valueMask |= effectiveValues[cells[i]];
      }

      if (countOnes16bit(valueMask) === cells.length) {
        const newHandler = new HandlerModule.PerfectAllDifferent(cells, valueMask);
        handlerSet.addNonEssential(newHandler);
        if (this._debugLogger) {
          this._logAddHandler('_addPerfectAllDifferentHandlers', newHandler);
        }
      }
    }
  }

  // Find {1-2}-cell sum constraints and replace them dedicated handlers.
  _replaceSizeSpecificSumHandlers(handlerSet, cellExclusions, geometry) {
    const maxSum = maxSumForShape(geometry);
    const sumHandlers = handlerSet.getAllofType(SumHandlerModule.Sum);
    for (const h of sumHandlers) {
      let newHandler;
      switch (h.cells.length) {
        case 1:
          {
            const sum = h.sum();
            const coeff = h.coefficients()[0];
            if (sum % coeff) {
              newHandler = new HandlerModule.False(h.cells);
            } else {
              newHandler = new HandlerModule.GivenCandidates(
                new Map([[h.cells[0], sum / coeff]]));
            }
          }
          break;

        case 2:
          {
            const cells = h.cells;
            const mutuallyExclusive = (
              cellExclusions.isMutuallyExclusive(...cells));
            const sum = h.sum();
            const [c0, c1] = h.coefficients();

            newHandler = new HandlerModule.BinaryConstraint(
              ...cells,
              fnToBinaryKey(
                (a, b) => a * c0 + b * c1 === sum && (!mutuallyExclusive || a !== b),
                geometry.numValues, geometry.valueOffset));
          }
          break;
        case geometry.numValues:
          {
            // If N cells are all pairwise mutually exclusive on a base-N grid,
            // then they must be a permutation of {1..N}. Therefore their sum is
            // fixed (maxSum(geometry)).
            // We handle this because some users add this constraint when they
            // could just add an AllDifferent constraint.
            if (!h.onlyUnitCoeffs()) break;
            if (!cellExclusions.areMutuallyExclusive(h.cells)) break;

            newHandler = (h.sum() === maxSum)
              ? new HandlerModule.True()
              : new HandlerModule.False(h.cells);
          }
      }

      if (newHandler) {
        handlerSet.replace(h, newHandler);
        if (this._debugLogger) {
          this._debugLogger.log({
            loc: '_replaceSizeSpecificSumHandlers',
            msg: 'Replace with: ' + newHandler.constructor.name,
            cells: newHandler.cells,
          });
        }
      }
    }
  }

  // Create a Sum handler out of all the cages sticking out of a fixed-sum
  // all-different region.
  _addSumIntersectionHandler(
    baseRegion, intersectingSumHandlers, gapRegions,
    removableRegionsBySize, cellExclusions, geometry) {
    const numSearchCells = cellExclusions.numSearchCells();
    let totalSum = 0;
    const candidateCells = new BitSet(numSearchCells);
    const baseCells = new BitSet(numSearchCells);
    for (const c of baseRegion.cells) baseCells.add(c);
    for (const h of intersectingSumHandlers) {
      totalSum += h.sum();
      for (const c of h.cells) candidateCells.add(c);
    }
    // Invariant from here: uncoveredBaseCells == baseCells - candidateCells.
    const uncoveredBaseCells = baseCells.clone();
    uncoveredBaseCells.subtract(candidateCells);

    // If we haven't filled up the entire region then try to greedily fill the
    // holes with intersecting all-different regions.
    let usedExtraRegions = false;
    if (!uncoveredBaseCells.isEmpty()) {
      for (const gapRegion of gapRegions) {
        // Ignore any regions which intersect with the existing cells.
        if (setIntersectSize(candidateCells, gapRegion.cells) > 0) continue;
        // Ignore any regions which don't cover the uncovered cells.
        const intersectSize = setIntersectSize(uncoveredBaseCells, gapRegion.cells);
        if (intersectSize === 0) continue;
        // Ignore handlers which only intersect in one square. This is likely
        // a row crossing a column, and is generally not useful.
        if (intersectSize === 1) continue;
        // Ensure the intersection only covers the uncovered cells.
        if (intersectSize !== setIntersectSize(baseCells, gapRegion.cells)) {
          continue;
        }
        // This handler fills in an existing gap.
        totalSum += gapRegion.sum;
        for (const c of gapRegion.cells) candidateCells.add(c);
        uncoveredBaseCells.subtract(candidateCells);
        usedExtraRegions = true;
        if (uncoveredBaseCells.isEmpty()) break;
      }
    }

    // If we still haven't covered all the cells, then give up.
    if (!uncoveredBaseCells.isEmpty()) return null;

    // Remove the current region cells, as we care about the cells outside the
    // region.
    candidateCells.subtract(baseCells);
    totalSum -= baseRegion.sum;

    // While it's possible that there could be another region completely
    // contained within the cells, then try to find and remove it.
    // Note that regions used to construct the cells won't match as we have
    // already removed the cells in the current region.
    let removedExtraRegions = false;
    let candidateCount = candidateCells.count();
    for (const region of removableRegionsBySize) {
      // Regions are sorted by increasing cellCount; once one region is larger
      // than candidateCells, all remaining regions are also too large.
      if (region.cellCount > candidateCount) break;
      // Ignore any regions which don't cover the cells.
      const intersectSize = setIntersectSize(candidateCells, region.cells);
      if (intersectSize !== region.cellCount) continue;
      // This region is completely contained within the cells.
      totalSum -= region.sum;
      for (const c of region.cells) candidateCells.remove(c);
      candidateCount -= region.cellCount;
      removedExtraRegions = true;
      if (candidateCount === 0) break;
    }

    if (candidateCount === 0) return null;

    // Use mutual-exclusion structure to estimate how restrictive this inferred
    // sum will be. Prefer sums that imply a narrow range relative to dof.
    // Sorted, so that the result is deterministic, and so that greedy grouping
    // naturally aligns on rows.
    const cellsArray = candidateCells.toSortedArray();
    const groups = HandlerModule.HandlerUtil.findExclusionGroupsGreedy(
      cellsArray, cellExclusions).groups;
    const { range, min, max } = HandlerModule.HandlerUtil.exclusionGroupSumInfo(
      groups, geometry.numValues, geometry.valueOffset);
    if (totalSum < min || totalSum > max) {
      // Infeasible sum, fail the puzzle.
      const handler = new HandlerModule.False(cellsArray);
      this._logAddHandler(
        '_addSumIntersectionHandler', handler, { totalSum, min, max });
      return handler;
    }

    const dof = Math.min(totalSum - min, max - totalSum);
    if (range === 0 || range <= 4 * dof) {
      if (this._debugLogger) {
        this._debugLogger.log({
          loc: '_addSumIntersectionHandler',
          msg: 'Skip',
          args: { sum: totalSum, range: range },
          cells: cellsArray,
        });
      }
      return null;
    }

    const handler = new SumHandlerModule.Sum(cellsArray, totalSum);

    if (this._debugLogger) {
      let args = {
        sum: handler.sum(), size: handler.cells.length,
        minSum: min, maxSum: max, range
      };
      if (usedExtraRegions) args.usedExtraRegions = usedExtraRegions;
      if (removedExtraRegions) args.removedExtraRegions = removedExtraRegions;
      this._logAddHandler('_addSumIntersectionHandler', handler, { args });
    }

    return handler;
  }

  // Find sets of cells which we can infer have a known sum and unique values.
  _makeHiddenCageHandlers(handlerSet, allSumHandlers, cellExclusions, geometry) {
    const allDiffRegions = fixedSumRegions(
      handlerSet.getAllofType(HandlerModule.PerfectAllDifferent),
      handlerSet, geometry);
    const allDiffRegionsBySize = [...allDiffRegions].sort(
      (a, b) => a.cellCount - b.cellCount);
    const allDiffRegionByIndex = new Map(
      allDiffRegions.map(region => [region.handlerIndex, region]));
    const newHandlers = [];

    const allSumHandlerIndexes = new BitSet(handlerSet.numHandlers());
    for (const h of allSumHandlers) allSumHandlerIndexes.add(handlerSet.getIndex(h));
    const allDiffHandlerIndexes = new BitSet(handlerSet.numHandlers());
    for (const region of allDiffRegions) allDiffHandlerIndexes.add(region.handlerIndex);
    // Reused across regions: each region is tested against every sum handler.
    const regionCells = new BitSet(cellExclusions.numSearchCells());
    // A handler's intersecting set depends on the handler, not the region, and
    // regions revisit the same sum handlers. Scoped to this pass only: adding
    // handlers changes the result, and the caller adds ours once we return.
    const intersectionCache = new Map();

    for (const baseRegion of allDiffRegions) {
      const h = baseRegion.handler;
      // Find sum constraints which overlap this region.
      const intersectingHandlers = handlerSet.getIntersectingIndexes(h);
      const currentRegionSumIndexes = intersectingHandlers.clone();
      currentRegionSumIndexes.intersect(allSumHandlerIndexes);
      if (currentRegionSumIndexes.isEmpty()) continue;

      // For the sum intersection, we need to ensure that the sum handlers don't
      // overlap themselves.
      // We do this separately for each region so that we don't have to force
      // the same handler to be used in every region it intersects.
      const filteredSumHandlers = this._findNonOverlappingSubset(
        currentRegionSumIndexes.toSortedArray().map(i => handlerSet.getHandler(i)),
        handlerSet, intersectionCache);

      {
        const currentRegionDiffIndexes = intersectingHandlers.clone();
        currentRegionDiffIndexes.intersect(allDiffHandlerIndexes);
        const intersectingAllDiffRegions = currentRegionDiffIndexes.toSortedArray().map(
          i => allDiffRegionByIndex.get(i));
        const sumIntersectionHandler = this._addSumIntersectionHandler(
          baseRegion, filteredSumHandlers, intersectingAllDiffRegions, allDiffRegionsBySize,
          cellExclusions, geometry);
        if (sumIntersectionHandler) newHandlers.push(sumIntersectionHandler);
      }

      // Outies are cages which stick out of the region by 1 cell.
      const outies = [];
      // Constrained cells are those from cages which are fully contained within
      // the region.
      const constrainedCells = [];
      let constrainedSum = 0;
      regionCells.clear();
      for (const c of h.cells) regionCells.add(c);
      for (const k of filteredSumHandlers) {
        const overlapSize = setIntersectSize(regionCells, k.cells);
        if (overlapSize === k.cells.length) {
          constrainedCells.push(...k.cells);
          constrainedSum += k.sum();
          k.setComplementCells(arrayDifference(h.cells, k.cells), h.valueMask());
        } else if (k.cells.length - overlapSize === 1) {
          outies.push(k);
        }
      }

      // Short-circuit the common case where there is nothing special in the
      // region.
      if (outies.length === 0 && constrainedCells.length === 0) continue;

      const complementCells = arrayDifference(h.cells, constrainedCells);
      const complementSum = baseRegion.sum - constrainedSum;

      // If a cage sticks out of a region by 1 cell, then we can form the
      // equivalent of an arrow sum (with offset). That is, the value of the
      // cell outside the region is a direct offset of the sum of the remaining
      // cells in the region outside the cage. The sum can be further reduced
      // by any other cages (i.e. known sums) in the region.
      for (const o of outies) {
        const remainingCells = arrayDifference(complementCells, o.cells);
        // Don't add sums with too many cells.
        if (remainingCells.length + 1 > this._MAX_SUM_SIZE) continue;

        const extraCells = arrayDifference(o.cells, h.cells);
        const remainingSum = complementSum - o.sum();
        const handlerCells = [...remainingCells, ...extraCells];
        const coeffs = handlerCells.map(
          (_, i) => i < remainingCells.length ? 1 : -1);
        const handler = new SumHandlerModule.Sum(
          handlerCells, remainingSum, coeffs);
        newHandlers.push(handler);

        if (this._debugLogger) {
          this._logAddHandler('_makeHiddenCageHandlers', handler, {
            args: { offset: remainingSum, negativeCells: [...extraCells] },
          });
        }
      }

      // No constraints within this region.
      if (constrainedCells.length === 0) continue;
      // A single remaining cell will already be constrained after the first pass.
      if (constrainedCells.length === 1) continue;
      // Nothing left to constrain.
      if (constrainedCells.length === baseRegion.cellCount) continue;

      const complementHandler = new SumHandlerModule.Sum(
        complementCells, complementSum);
      complementHandler.setComplementCells(constrainedCells, h.valueMask());
      newHandlers.push(complementHandler);
      if (this._debugLogger) {
        this._logAddHandler('_makeHiddenCageHandlers', complementHandler, {
          args: { sum: complementSum },
        });
      }
    }

    return newHandlers;
  }

  // Add same value handlers for intersections between jigsaw pieces and other
  // fixed-value regions.
  _makeJigsawIntersections(handlerSet, jigsawPieces) {
    const allHandlers = handlerSet.getAllofType(HandlerModule.PerfectAllDifferent);
    const cellsKey = (cells) => sortedArrayCopy(cells).join(',');
    const pieceKeys = new Set(jigsawPieces.map(p => cellsKey(p.cells)));
    const isPiece = allHandlers.map(h => pieceKeys.has(cellsKey(h.cells)));
    const newHandlers = [];

    // Add constraints due to overlapping regions. Pairs of plain grid houses
    // are handled by _addGridHouseIntersections, so require a jigsaw piece in
    // each pair.
    for (let i = 1; i < allHandlers.length; i++) {
      const h0 = allHandlers[i];
      for (let j = 0; j < i; j++) {
        if (!isPiece[i] && !isPiece[j]) continue;
        const h1 = allHandlers[j];
        if (h0.cells.length !== h1.cells.length) continue;
        if (h0.valueMask() !== h1.valueMask()) continue;

        const diff0 = arrayDifference(h0.cells, h1.cells);
        if (
          // Skip identical regions.
          diff0.length === 0
          // Also diffs that are too large.
          || diff0.length > this._MAX_SUM_SIZE
          // Ensure overlap is more than one cell.
          || diff0.length >= h0.cells.length - 1) continue;

        // We have some overlapping cells!
        // This means diff0 and diff1 must contain the same values.
        const diff1 = arrayDifference(h1.cells, h0.cells);

        // TODO: Optimize the diff0.length === 1 case (and 2?).
        const handler = new HandlerModule.SameValuesIgnoreCount(diff0, diff1);
        newHandlers.push(handler);
        this._logAddHandler('_makeJigsawIntersections', handler);
      }
    }

    return newHandlers;
  }

  // Returns region-groups used by the jigsaw overlap optimizations.
  // An axis forms regions when its cells-per-region equals valueCount.
  _overlapRegions(geometry, boxRegions, valueCount) {
    const regions = [];

    // Rows and columns are only houses on a Sudoku grid.
    const isSudoku = geometry.gridType === CellGeometry.SUDOKU_GRID_TYPE;

    // Rows are houses if they have valueCount cells (numCols === valueCount).
    if (isSudoku && geometry.numCols === valueCount) {
      const rowRegions = SudokuConstraintBase.rowRegions(geometry);
      regions.push(rowRegions, rowRegions.slice().reverse());
    }

    // Columns are houses if they have valueCount cells (numRows === valueCount).
    if (isSudoku && geometry.numRows === valueCount) {
      const colRegions = SudokuConstraintBase.colRegions(geometry);
      regions.push(colRegions, colRegions.slice().reverse());
    }

    if (boxRegions.length > 0 && boxRegions[0].length === valueCount) {
      regions.push(boxRegions);
    }

    return regions;
  }

  // Attach an aux handler to each Rellik cage that forces into the cage any
  // value an overlapping house can only place inside it (see HouseRequiredRellik).
  _optimizeRellik(handlerSet, geometry) {
    const rellikHandlers = handlerSet.getAllofType(HandlerModule.Rellik);
    if (rellikHandlers.length === 0) return;

    const houses = handlerSet.getAllofType(HandlerModule.PerfectAllDifferent);
    if (houses.length === 0) return;

    for (const r of rellikHandlers) {
      const cageSet = new Set(r.cells);
      for (const house of houses) {
        const cells = house.cells;
        const interCount = setIntersectSize(cageSet, cells);
        // A single overlapping cell is just a hidden single (handled
        // elsewhere); a cage covering the whole house has no outside cells to
        // reason from.
        if (interCount < 2 || interCount === cells.length) continue;

        const handler = new HandlerModule.HouseRequiredRellik(
          r, arrayDifference(cells, r.cells), house.valueMask());
        handlerSet.addNonEssential(handler);
        this._logAddHandler('_optimizeRellik', handler);
      }
    }
  }

  // `superRegion` and `piecesRegion` are passed to the callback as BitSets of
  // cells, sized to numSearchCells.
  _generalRegionOverlapProcessor(regions, pieces, numSearchCells, callback) {
    const numValues = regions.length;
    const superRegion = new BitSet(numSearchCells);
    const remainingPieces = new Set(pieces);
    const usedPieces = [];
    const piecesRegion = new BitSet(numSearchCells);

    let i = 0;
    for (const r of regions) {
      i++;
      if (i === numValues) break;

      // Add r to our super-region.
      for (const c of r) superRegion.add(c);

      // Add any remaining pieces with enough overlap to our super-region.
      for (const p of remainingPieces) {
        const intersectionSize = setIntersectSize(superRegion, p);
        if (intersectionSize > p.length / 2) {
          remainingPieces.delete(p);
          for (const c of p) piecesRegion.add(c);
          usedPieces.push(p);
        }
      }

      // Don't process the first region, as that usually doubles up work from
      // elsewhere.
      if (i === 1) continue;

      callback(superRegion, piecesRegion, usedPieces);
    }
  }

  _makeJigsawLawOfLeftoverHandlers(
    jigsawPieces, boxRegions, geometry, effectiveValueCount) {
    const newHandlers = [];
    const pieces = jigsawPieces.map(p => p.cells);

    const handleOverlap = (superRegion, piecesRegion, usedPieces) => {
      // We can only match when regions are the same size.
      if (superRegion.count() !== piecesRegion.count()) return;

      const diffA = superRegion.clone();
      diffA.subtract(piecesRegion);
      const diffASize = diffA.count();
      if (diffASize === 0) return;
      const diffB = piecesRegion.clone();
      diffB.subtract(superRegion);
      // Ignore diff that too big, they are probably not very well
      // constrained.
      if (diffASize >= geometry.numValues) return;

      // All values in the set differences must be the same.
      const newHandler = new HandlerModule.SameValuesIgnoreCount(
        diffA.toSortedArray(), diffB.toSortedArray());
      newHandlers.push(newHandler);
      this._logAddHandler('_makeJigsawLawOfLeftoverHandlers', newHandler);
    }

    for (const r of this._overlapRegions(geometry, boxRegions, effectiveValueCount)) {
      this._generalRegionOverlapProcessor(
        r, pieces, geometry.totalCells(), handleOverlap);
    }

    return newHandlers;
  }

  _makeInnieOutieSumHandlers(
    sumHandlers, boxRegions, geometry, effectiveValueCount = geometry.numValues,
    effectiveValueSum = maxSumForShape(geometry)) {
    const newHandlers = [];

    const pieces = sumHandlers.map(h => h.cells);
    const piecesMap = new Map(sumHandlers.map(h => [h.cells, h.sum()]));

    const cellsInSum = new BitSet(geometry.totalCells());
    for (const h of sumHandlers) for (const c of h.cells) cellsInSum.add(c);

    const handleOverlap = (superRegion, piecesRegion, usedPieces) => {
      let diffA = superRegion.clone();
      diffA.subtract(piecesRegion);
      let diffB = piecesRegion.clone();
      diffB.subtract(superRegion);
      let sizeA = diffA.count();
      let sizeB = diffB.count();

      // No diff, no new constraints to add.
      if (sizeA === 0 && sizeB === 0) return;
      // Don't use this if the diff is too large.
      if (sizeA + sizeB > effectiveValueCount) return;

      // We can only do negative sum constraints when the diff is 1.
      // We can only do sum constraints when the diff is 0.
      if (sizeA > 2 && sizeB > 2) return;

      if (cellsInSum.hasAll(diffA) && cellsInSum.hasAll(diffB)) {
        // If all cells in the diff overlap with a piece, then limit the size of
        // the sum.
        if (sizeA + sizeB > this._MAX_SUM_SIZE) return;
        // Otherwise we are adding a sum constraint to a cell which doesn't
        // currently have one, so we'll take all the help we can get!
      }

      let sumDelta = -superRegion.count() * effectiveValueSum / effectiveValueCount;
      for (const p of usedPieces) sumDelta += piecesMap.get(p);

      // Ensure diffA is the smaller.
      if (sizeA > sizeB) {
        [diffA, diffB] = [diffB, diffA];
        [sizeA, sizeB] = [sizeB, sizeA];
        sumDelta = -sumDelta;
      }

      let newHandler;
      let args;
      const sortedDiffB = diffB.toSortedArray();
      if (sizeA === 0) {
        newHandler = new SumHandlerModule.Sum(sortedDiffB, sumDelta);
        args = { sum: sumDelta };
      } else {
        const sortedDiffA = diffA.toSortedArray();
        const newHandlerCells = [...sortedDiffB, ...sortedDiffA];
        const coeffs = newHandlerCells.map((_, i) => i < sizeB ? 1 : -1);
        newHandler = new SumHandlerModule.Sum(
          newHandlerCells, sumDelta, coeffs);
        args = { sum: sumDelta, negativeCells: sortedDiffA };
      }

      newHandlers.push(newHandler);
      this._logAddHandler('_makeInnieOutieSumHandlers', newHandler, { args });
    };

    for (const r of this._overlapRegions(geometry, boxRegions, effectiveValueCount)) {
      this._generalRegionOverlapProcessor(
        r, pieces, geometry.totalCells(), handleOverlap);
    }

    return newHandlers;
  }

  _optimizeFullRank(handlerSet, geometry) {
    const rankHandlers = handlerSet.getAllofType(HandlerModule.FullRank);
    if (rankHandlers.length === 0) return;

    const clues = [];
    let tieMode = HandlerModule.FullRank.TIE_MODE.ANY;
    for (const h of rankHandlers) {
      clues.push(...h.clues());
      tieMode = Math.min(tieMode, h.tieMode());
      handlerSet.replace(h, new HandlerModule.True());
    }

    // Reuse FullRank's entry construction so we stay in sync.
    const entries = HandlerModule.FullRank.buildEntries(geometry);
    const equalsKey = SudokuConstraintOptimizer._equalsKey(geometry.numValues);

    // Dedupe. Keep the first clue per rank; if we see a duplicate rank,
    // enforce entry equality against the representative.
    const dedupedClues = [];
    const seenRank = new Set();
    for (const clue of clues) {
      if (!seenRank.has(clue.rank)) {
        seenRank.add(clue.rank);
        dedupedClues.push(clue);
        continue;
      }

      // This is a duplicate rank clue, look for the duplicates and stop when
      // we find it (it is guaranteed to be there).
      for (const existingClue of dedupedClues) {
        if (clue.rank !== existingClue.rank) continue;

        const aEntry = HandlerModule.FullRank.entryFromClue(entries, clue);
        const bEntry = HandlerModule.FullRank.entryFromClue(entries, existingClue);
        if (!aEntry || !bEntry) break;

        // TODO: These don't benefit for sharing the same exclusion sets,
        // which is optimized in _addExtraCellExclusions.
        for (let j = 0; j < aEntry.length; j++) {
          const a = aEntry[j];
          const b = bEntry[j];
          if (a === b) continue;
          const eq = new HandlerModule.BinaryConstraint(a, b, equalsKey);
          handlerSet.add(eq);
          this._logAddHandler('_optimizeFullRank', eq, {
            args: { rank: clue.rank },
          });
        }
        break;
      }
    }

    const handler = new HandlerModule.FullRank(
      geometry.numGridCells, dedupedClues, tieMode);
    handlerSet.add(handler);

    if (this._debugLogger) {
      this._debugLogger.log({
        loc: '_optimizeFullRank',
        msg: 'Combine: ' + handler.constructor.name,
        args: {
          numHandlers: rankHandlers.length,
          numClues: clues.length,
          numDedupedClues: dedupedClues.length,
          tieMode,
        },
        cells: handler.cells
      });
    }
  }

  _getForbiddenStack(numWords, count) {
    if (!this._forbiddenStackPool ||
      this._forbiddenStackPool.numWords !== numWords ||
      this._forbiddenStackPool.count < count) {
      this._forbiddenStackPool = BitSet.allocatePool(numWords * 32, count);
      this._forbiddenStackPool.numWords = numWords;
      this._forbiddenStackPool.count = count;
    }
    return this._forbiddenStackPool.bitsets;
  }

  // Find values which must or must not be in certain cells.
  // Returns false if there are no possible combinations, true otherwise.
  _findKnownRequiredValues(cells, value, count, cellExclusions, restrictions, exclusionGroups) {
    const numCells = cells.length;
    if (count > exclusionGroups.length) return false;

    // Estimate complexity to avoid running too long.
    const groupSizes = exclusionGroups.map(g => g.length);
    const MAX_NODES = 120;
    if (elementarySymmetricSum(groupSizes, count) > MAX_NODES) return true;

    const occurrences = new Int16Array(numCells);
    let numCombinations = 0;

    const numGroups = exclusionGroups.length;
    const stack = new Int16Array(numGroups);

    // Values in stack are initialized to -2.
    // The first increment results in -1 (SKIP).
    // If skipping is not allowed, we increment again to 0 (first item).
    const STATE_INITIAL = -2;
    const STATE_SKIP = -1;

    if (numGroups > 0) stack[0] = STATE_INITIAL;
    let stackDepth = 0;

    const pickedCounts = new Int16Array(numGroups + 1);

    // Use BitSets for O(1) checks.
    const numWords = cellExclusions.getBitSet(cells[0]).words.length;
    const forbiddenStack = this._getForbiddenStack(numWords, numGroups + 1);
    forbiddenStack[0].clear();

    while (stackDepth >= 0) {
      const groupIndex = stackDepth;
      const group = exclusionGroups[groupIndex];

      let choice = stack[stackDepth];
      choice++;

      if (choice === STATE_SKIP) {
        const remainingGroups = numGroups - 1 - stackDepth;
        if (pickedCounts[stackDepth] + remainingGroups < count) {
          choice++;
        }
      }

      if (choice >= 0) {
        const forbidden = forbiddenStack[stackDepth];
        while (choice < group.length) {
          if (!forbidden.has(cells[group[choice]])) break;
          choice++;
        }
      }

      if (choice >= group.length) {
        stackDepth--;
        continue;
      }

      stack[stackDepth] = choice;

      let nextPickedCount = pickedCounts[stackDepth];
      if (choice >= 0) nextPickedCount++;

      if (nextPickedCount === count) {
        numCombinations++;
        for (let i = 0; i <= stackDepth; i++) {
          const c = stack[i];
          if (c >= 0) {
            occurrences[exclusionGroups[i][c]]++;
          }
        }
      } else {
        const nextDepth = stackDepth + 1;
        if (nextDepth < numGroups) {
          pickedCounts[nextDepth] = nextPickedCount;
          const nextForbidden = forbiddenStack[nextDepth];
          nextForbidden.copyFrom(forbiddenStack[stackDepth]);
          if (choice >= 0) {
            nextForbidden.union(cellExclusions.getBitSet(cells[group[choice]]));
          }

          stack[nextDepth] = STATE_INITIAL;
          stackDepth++;
        }
      }
    }

    if (numCombinations === 0) return false;

    for (let i = 0; i < numCells; i++) {
      if (occurrences[i] === numCombinations) {
        if (!restrictions.has(cells[i])) restrictions.set(cells[i], []);
        restrictions.get(cells[i]).push({ require: value });
      } else if (occurrences[i] === 0) {
        if (!restrictions.has(cells[i])) restrictions.set(cells[i], []);
        restrictions.get(cells[i]).push({ remove: value });
      }
    }

    return true;
  }

  _optimizeRequiredValues(handlerSet, cellExclusions, geometry) {
    const requiredValueHandlers = handlerSet.getAllofType(HandlerModule.RequiredValues);
    if (requiredValueHandlers.length === 0) return;

    for (const h of requiredValueHandlers) {
      const restrictions = new Map();
      const exclusionGroups = HandlerModule.HandlerUtil.findMappedExclusionGroups(
        h.cells, cellExclusions).groups;
      // Sort groups by size to optimize search order.
      // Smallest first makes it more likely we can skip larger groups.
      exclusionGroups.sort((a, b) => a.length - b.length);

      // Brute force search for values which are restricted to certain cells.
      for (const [value, count] of h.valueCounts().entries()) {
        if (count > 1) {
          if (!this._findKnownRequiredValues(
            h.cells, value, count, cellExclusions, restrictions, exclusionGroups)) {
            // There were NO combinations found, so this handler is invalid.
            const newHandler = new HandlerModule.False(h.cells);
            handlerSet.replace(h, newHandler);
            if (this._debugLogger) {
              this._debugLogger.log({
                loc: '_optimizeRequiredValues',
                msg: 'Replace with: ' + newHandler.constructor.name,
                cells: newHandler.cells,
              });
            }
          }
        }
      }

      // If there are restrictions, then apply them.
      if (restrictions.size > 0) {
        const newValues = [...h.values()];
        const newCells = [...h.cells];
        const handlerValues = new Set(h.values());
        const allValues = LookupTables.toOffsetValuesArray(
          LookupTables.get(geometry.numValues).allValues,
          geometry.valueOffset);

        // Convert {require}/{remove} lists to allowed value arrays.
        const givenCandidates = new Map();
        for (const [cell, ops] of restrictions) {
          let allowed = allValues.slice();
          for (const op of ops) {
            if (op.require !== undefined) {
              allowed = allowed.filter(v => v === op.require);
            }
            if (op.remove !== undefined) {
              arrayRemoveValue(allowed, op.remove);
            }
          }
          givenCandidates.set(cell, allowed);
          // If only one value is allowed, then the value is known and we can
          // remove it from the RequiredValues handler.
          if (allowed.length === 1) {
            arrayRemoveValue(newValues, allowed[0]);
            arrayRemoveValue(newCells, cell);
          }
          // If none of the currently allowed values are in the required set
          // then we can remove this cell from the RequiredValues handler.
          if (!allowed.some(v => handlerValues.has(v))) {
            arrayRemoveValue(newCells, cell);
          }
        }

        // Create a handler to restrict the values.
        const newHandler = new HandlerModule.GivenCandidates(
          givenCandidates);
        handlerSet.add(newHandler);
        if (this._debugLogger) {
          this._logAddHandler('_optimizeRequiredValues', newHandler, {
            args: { restrictions: Object.fromEntries(givenCandidates.entries()) },
            cells: h.cells,
          });
        }

        // Replace the old handler if we can remove some cells.
        if (newValues.length === 0) {
          handlerSet.delete(h);
          if (this._debugLogger) {
            this._debugLogger.log({
              loc: '_optimizeRequiredValues',
              msg: 'Delete (no more values): ' + newHandler.constructor.name,
              cells: h.cells,
            });
          }
        } else if (newCells.length !== h.cells.length) {
          const newHandler = new HandlerModule.RequiredValues(
            newCells, newValues, h.isStrict());
          handlerSet.replace(h, newHandler);
          if (this._debugLogger) {
            this._debugLogger.log({
              loc: '_optimizeRequiredValues',
              msg: 'Replace with: ' + newHandler.constructor.name,
              args: { newValues },
              cells: newHandler.cells,
            });
          }
        }
      }
    }
  }

  _optimizeTaxicab(handlerSet, cellExclusions, geometry) {
    const taxicabHandlers = handlerSet.getAllofType(
      HandlerModule.ValueDependentUniqueValueExclusion);
    if (taxicabHandlers.length === 0) return;

    const valueCellExclusions = [];
    for (let i = 1; i <= geometry.numValues; i++) {
      const valueCellExclusion = cellExclusions.clone();
      valueCellExclusions.push(valueCellExclusion);
      for (const h of taxicabHandlers) {
        const cell = h.cells[0];
        for (const otherCell of h.getValueCellExclusions(i)) {
          valueCellExclusion.addMutualExclusion(cell, otherCell);
        }
      }
    }

    for (const h of handlerSet.getAllofType(HandlerModule.PerfectAllDifferent)) {
      const newHandler = new HandlerModule.PerfectAllDifferentValueExclusion(
        h.cells, valueCellExclusions);
      handlerSet.add(newHandler);
      this._logAddHandler('_optimizeTaxicab', newHandler);
    }
  }

  // Replace 2-cell BinaryPairwise handlers with a direct BinaryConstraint
  // handler. This has less overhead both during runtime and initialization.
  _optimizeBinaryPairwise(handlerSet, geometry) {
    const handlers = handlerSet.getAllofType(HandlerModule.BinaryPairwise);
    for (const h of handlers) {
      if (h.cells.length !== 2) continue;
      h.validate(geometry.numValues);  // Validate so we preserve behaviour.
      const newHandler = new HandlerModule.BinaryConstraint(
        ...h.cells, h.key());
      handlerSet.replace(h, newHandler);
      if (this._debugLogger) {
        this._debugLogger.log({
          loc: '_optimizeBinaryPairwise',
          msg: 'Replace with: ' + newHandler.constructor.name,
          cells: newHandler.cells,
        });
      }
    }
  }

  _logStats(handlerSet) {
    if (!this._debugLogger) return;

    const mask = (1 << 16) - 1;

    for (const h of handlerSet.getAllofType(NFAModule.NFAConstraint)) {
      const cnfa = h.getNFA();
      let numTransitionEntries = 0;
      let isDFA = true;
      for (const transitions of cnfa.transitionLists) {
        numTransitionEntries += transitions.length;
        let seen = 0;
        for (const t of transitions) {
          if (t & mask & seen) isDFA = false;
          seen |= t & mask;
        }
      }
      const stateType = isDFA ? ' (DFA)' : '';
      this._debugLogger.log({
        loc: '_logStats',
        msg: `NFAConstraint with ${cnfa.numStates} states, ${numTransitionEntries} transition entries${stateType}`,
        cells: h.cells,
      });
    }
  }
}

